// Determine which addresses to use based on environment
const isDevelopment = process.env.NODE_ENV === 'development';
const useLocalhost = process.env.NEXT_PUBLIC_USE_LOCALHOST === 'true';

export const CONTRACT_ADDRESSES = (isDevelopment || useLocalhost) 
  ? LOCALHOST_ADDRESSES 
  : ARBITRUM_SEPOLIA_ADDRESSES;

export type ContractName = keyof typeof CONTRACT_ADDRESSES;

export const getContractAddress = (name: ContractName): string => {
  const address = CONTRACT_ADDRESSES[name];
  if (!address || address === "0x0000000000000000000000000000000000000000") {
    throw new Error(`Contract ${name} not deployed or address not set`);
  }
  return address;
};